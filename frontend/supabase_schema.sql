-- 1. Bảng Nhóm hàng (categories)
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    english_name VARCHAR(120),
    description VARCHAR(255) DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

-- 2. Bảng Đơn vị tính (units)
CREATE TABLE IF NOT EXISTS public.units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) NOT NULL UNIQUE,
    english_name VARCHAR(60)
);

-- 3. Bảng Hàng hóa (products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    english_name VARCHAR(255),
    barcode VARCHAR(100),
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    category_name VARCHAR(120) NOT NULL DEFAULT '',
    price BIGINT NOT NULL DEFAULT 0 CHECK (price >= 0),
    cost BIGINT NOT NULL DEFAULT 0 CHECK (cost >= 0),
    unit VARCHAR(60) NOT NULL DEFAULT '',
    stock DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    min_stock_threshold DOUBLE PRECISION NOT NULL DEFAULT 5.0,
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    updated_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

CREATE INDEX IF NOT EXISTS idx_products_name ON public.products(name);
CREATE INDEX IF NOT EXISTS idx_products_barcode ON public.products(barcode);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category_name);

-- 4. Bảng Khách hàng (customers)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    phone VARCHAR(50) NOT NULL UNIQUE,
    address VARCHAR(350) NOT NULL DEFAULT '',
    note VARCHAR(500) NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    updated_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

CREATE INDEX IF NOT EXISTS idx_customers_name ON public.customers(name);
CREATE INDEX IF NOT EXISTS idx_customers_phone ON public.customers(phone);

-- 5. Bảng Hóa đơn (invoices)
CREATE TABLE IF NOT EXISTS public.invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE,
    date BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    subtotal_amount BIGINT NOT NULL DEFAULT 0,
    discount_amount BIGINT NOT NULL DEFAULT 0,
    total_amount BIGINT NOT NULL DEFAULT 0,
    total_cost BIGINT NOT NULL DEFAULT 0,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'cash',
    note VARCHAR(500),
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_invoices_date ON public.invoices(date DESC);
CREATE INDEX IF NOT EXISTS idx_invoices_customer_id ON public.invoices(customer_id);

-- 6. Bảng Chi tiết Hóa đơn (invoice_items)
CREATE TABLE IF NOT EXISTS public.invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES public.invoices(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    product_name_snapshot VARCHAR(255) NOT NULL DEFAULT '',
    unit_snapshot VARCHAR(60) NOT NULL DEFAULT '',
    quantity DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    price BIGINT NOT NULL DEFAULT 0,
    cost BIGINT NOT NULL DEFAULT 0,
    sub_total BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice_id ON public.invoice_items(invoice_id);
CREATE INDEX IF NOT EXISTS idx_invoice_items_product_id ON public.invoice_items(product_id);

-- 7. Bảng Thẻ kho / Lịch sử biến động tồn kho (stock_movements)
CREATE TABLE IF NOT EXISTS public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    movement_type VARCHAR(50) NOT NULL,
    quantity_change DOUBLE PRECISION NOT NULL,
    stock_before DOUBLE PRECISION NOT NULL,
    stock_after DOUBLE PRECISION NOT NULL,
    reference_code VARCHAR(100),
    note VARCHAR(255) NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

CREATE INDEX IF NOT EXISTS idx_stock_movements_product_id ON public.stock_movements(product_id, created_at DESC);

-- 8. Bảng Sổ nợ (debt_records)
CREATE TABLE IF NOT EXISTS public.debt_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT REFERENCES public.invoices(id) ON DELETE SET NULL,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    customer_name VARCHAR(200) NOT NULL,
    customer_phone VARCHAR(50),
    amount BIGINT NOT NULL,
    paid_amount BIGINT NOT NULL DEFAULT 0,
    note VARCHAR(500) NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    due_date BIGINT,
    is_settled BOOLEAN NOT NULL DEFAULT FALSE,
    settled_at BIGINT
);

CREATE INDEX IF NOT EXISTS idx_debt_records_customer_id ON public.debt_records(customer_id);
CREATE INDEX IF NOT EXISTS idx_debt_records_is_settled ON public.debt_records(is_settled, created_at DESC);

-- 9. Bảng Lịch sử thanh toán công nợ (debt_payments)
CREATE TABLE IF NOT EXISTS public.debt_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debt_id BIGINT NOT NULL REFERENCES public.debt_records(id) ON DELETE CASCADE,
    amount BIGINT NOT NULL,
    payment_method VARCHAR(50) NOT NULL DEFAULT 'cash',
    note VARCHAR(255) NOT NULL DEFAULT '',
    paid_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

CREATE INDEX IF NOT EXISTS idx_debt_payments_debt_id ON public.debt_payments(debt_id);

-- 10. Bảng Tài khoản ngân hàng VietQR (bank_accounts)
CREATE TABLE IF NOT EXISTS public.bank_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_code VARCHAR(50) NOT NULL,
    bank_name VARCHAR(255) NOT NULL,
    account_number VARCHAR(100) NOT NULL UNIQUE,
    account_name VARCHAR(200) NOT NULL,
    bin_code VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

-- 11. Bảng Hóa đơn nháp (invoice_drafts)
CREATE TABLE IF NOT EXISTS public.invoice_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    updated_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT,
    total_amount BIGINT NOT NULL DEFAULT 0,
    total_items INTEGER NOT NULL DEFAULT 0,
    items_json TEXT NOT NULL,
    customer_id BIGINT,
    customer_name VARCHAR(200),
    note VARCHAR(255) DEFAULT ''
);

-- 12. Bảng Người dùng & Phân quyền (app_users)
CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(200) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'cashier',
    permissions_json TEXT NOT NULL DEFAULT '{}',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

